//! Интеграция с OpenWrt: что открывается по адресу роутера (cgmon или LuCI) и DNS-имена
//! роутера (router.lan, cgmon.lan…), по которым всегда открывается cgmon.
//!
//! Стартовая страница — /www/index.html, которую отдаёт uhttpd. cgmon пишет её со своей
//! меткой, прежнюю (стоковую или свою) сохраняет рядом и возвращает, когда интеграцию
//! выключили. Имена — файл dnsmasq `interface-name=имя,br-lan` (адрес роутера в той сети,
//! откуда спросили), перезапуск dnsmasq — только когда файл изменился.

use std::sync::mpsc::Receiver;

const INDEX: &str = "/www/index.html";
const BACKUP: &str = "/www/index.html.cgmon-orig";
const MARK: &str = "<!-- cgmon-index -->";
const DNSMASQ_FILE: &str = "cgmon-names.conf";

/// Стоковая index.html OpenWrt — если сохранённой копии нет.
const STOCK: &str = "<!DOCTYPE html>\n<html>\n<head>\n<meta http-equiv=\"Cache-Control\" content=\"no-cache\" />\n<meta http-equiv=\"refresh\" content=\"0; URL=cgi-bin/luci/\" />\n</head>\n<body style=\"background-color: white\">\n<a style=\"color: black; font-family: arial, helvetica, sans-serif;\" href=\"cgi-bin/luci/\">LuCI - Lua Configuration Interface</a>\n</body>\n</html>\n";

#[derive(Default)]
pub struct Integration {
    sig: String,
    checked: u64,
    dm_busy: Option<Receiver<bool>>,
    pub err: String,
}

/// Имена: нижний регистр, только допустимые символы, без повторов.
pub fn clean_names(names: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for n in names {
        let n = n.trim().trim_end_matches('.').to_ascii_lowercase();
        if !n.is_empty() && n.len() <= 253 && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '.') && !out.contains(&n) {
            out.push(n);
        }
    }
    out
}

/// Текст стартовой страницы: cgmon (по умолчанию или по имени) или LuCI.
pub fn index_html(home_cgmon: bool, names: &[String]) -> String {
    let list = names.iter().map(|n| format!("'{n}'")).collect::<Vec<_>>().join(",");
    format!(
        "<!DOCTYPE html>\n{MARK}\n<html>\n<head>\n<meta charset=\"utf-8\">\n<meta http-equiv=\"Cache-Control\" content=\"no-cache, no-store, must-revalidate\">\n<title>OpenWrt</title>\n<script>\n// generated by cgmon (Settings → cgmon: data and integration); the previous file is {BACKUP}\nvar h = location.hostname.toLowerCase(), names = [{list}];\nvar cg = {home} || names.indexOf(h) >= 0 || names.some(function (n) {{ return n.split('.')[0] === h; }});\nlocation.replace(cg ? '/status.html' : '/cgi-bin/luci/');\n</script>\n</head>\n<body>\n<a href=\"/status.html\">cgmon</a> · <a href=\"/cgi-bin/luci/\">LuCI (OpenWrt)</a>\n</body>\n</html>\n",
        home = if home_cgmon { "true" } else { "false" }
    )
}

/// Файл dnsmasq с именами роутера.
pub fn dnsmasq_names(names: &[String], dev: &str) -> String {
    if names.is_empty() {
        return String::new();
    }
    let mut s = String::from("# cgmon: router names (Settings → cgmon: data and integration) — generated\n");
    for n in names {
        s.push_str(&format!("interface-name={n},{dev}\n"));
    }
    s
}

/// Устройство сети lan (br-lan).
fn lan_dev() -> String {
    crate::flowwatch::output_timeout("ifstatus", &["lan"], 3000)
        .and_then(|t| crate::value::parse_json(&t).ok())
        .and_then(|v| v.get("l3_device").and_then(|x| x.as_str()).map(String::from))
        .filter(|d| !d.is_empty())
        .unwrap_or_else(|| "br-lan".into())
}

impl Integration {
    /// Раз в минуту (и сразу после смены настроек) — привести файлы к настройкам.
    pub fn tick(&mut self, now_ms: u64, home: &str, names: &[String]) -> Vec<String> {
        let mut msgs = Vec::new();
        if let Some(rx) = &self.dm_busy {
            match rx.try_recv() {
                Ok(ok) => {
                    if !ok {
                        self.err = tr!("dnsmasq: не удалось перезапустить").to_string();
                    }
                    self.dm_busy = None;
                }
                Err(std::sync::mpsc::TryRecvError::Empty) => {}
                Err(_) => self.dm_busy = None,
            }
        }
        let names = clean_names(names);
        let home_cgmon = home == "cgmon";
        let sig = format!("{home}|{}", names.join(","));
        if sig == self.sig && now_ms.saturating_sub(self.checked) < 60_000 {
            return msgs;
        }
        self.checked = now_ms;
        let first = self.sig.is_empty();
        self.sig = sig;
        if crate::util::readonly() || !std::path::Path::new("/www").is_dir() {
            return msgs;
        }
        self.err.clear();
        // стартовая страница
        let cur = std::fs::read_to_string(INDEX).unwrap_or_default();
        if home_cgmon || !names.is_empty() {
            let want = index_html(home_cgmon, &names);
            if cur != want {
                if !cur.contains(MARK) && !std::path::Path::new(BACKUP).exists() && !cur.is_empty() {
                    let _ = std::fs::write(BACKUP, &cur);
                }
                match crate::util::write_atomic(INDEX, want.as_bytes(), 0o644) {
                    Ok(()) => msgs.push(if home_cgmon { tr!("Интеграция: по адресу роутера теперь открывается cgmon, LuCI — по ссылке на странице").to_string() } else { tr!("Интеграция: cgmon открывается по именам {}", names.join(", ")).to_string() }),
                    Err(e) => self.err = format!("{INDEX}: {e}"),
                }
            }
        } else if cur.contains(MARK) {
            let back = std::fs::read_to_string(BACKUP).ok().filter(|b| !b.contains(MARK)).unwrap_or_else(|| STOCK.to_string());
            match crate::util::write_atomic(INDEX, back.as_bytes(), 0o644) {
                Ok(()) => {
                    let _ = std::fs::remove_file(BACKUP);
                    msgs.push(tr!("Интеграция: стартовая страница роутера возвращена (LuCI)").to_string());
                }
                Err(e) => self.err = format!("{INDEX}: {e}"),
            }
        }
        // имена в DNS
        let Some(dir) = crate::persite::conf_dir() else {
            if !names.is_empty() {
                self.err = tr!("dnsmasq не найден — имена роутера не заданы").to_string();
            }
            return msgs;
        };
        let path = format!("{dir}/{DNSMASQ_FILE}");
        let want = dnsmasq_names(&names, &lan_dev());
        let cur = std::fs::read_to_string(&path).unwrap_or_default();
        if want != cur && self.dm_busy.is_none() {
            let r = if want.is_empty() { std::fs::remove_file(&path).map_err(|e| e.to_string()) } else { crate::util::write_atomic(&path, want.as_bytes(), 0o644).map_err(|e| e.to_string()) };
            if let Err(e) = r {
                self.err = format!("{path}: {e}");
                return msgs;
            }
            let (tx, rx) = std::sync::mpsc::channel();
            self.dm_busy = Some(rx);
            let _ = std::thread::Builder::new().name("integr-dnsmasq".into()).spawn(move || {
                let ok = std::process::Command::new("/etc/init.d/dnsmasq").arg("restart").stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).status().map_or(false, |s| s.success());
                let _ = tx.send(ok);
            });
            if !names.is_empty() || !first {
                msgs.push(if names.is_empty() { tr!("Интеграция: имена роутера убраны из DNS").to_string() } else { tr!("Интеграция: имена роутера в DNS — {}", names.join(", ")).to_string() });
            }
        }
        msgs
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_and_files() {
        let n = clean_names(&["ROUTER.lan.".into(), "cgmon.lan".into(), "bad name".into(), "router.lan".into()]);
        assert_eq!(n, vec!["router.lan".to_string(), "cgmon.lan".to_string()]);
        let h = index_html(false, &n);
        assert!(h.contains(MARK) && h.contains("'router.lan','cgmon.lan'") && h.contains("var cg = false"));
        assert!(dnsmasq_names(&n, "br-lan").contains("interface-name=cgmon.lan,br-lan"));
        assert!(dnsmasq_names(&[], "br-lan").is_empty());
    }
}
