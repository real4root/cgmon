//! Справка: --help (кратко) и --help-advanced (подробно, как man) — перенос help.go.

pub fn short() -> String {
    format!(
        "cgmon {} — монитор WAN, conntrack/NAT и устройств для OpenWrt/ImmortalWrt

Использование:
  cgmon [команда] [-config ФАЙЛ]

Основные команды:
  daemon               запуск демона (по умолчанию; обычно — служба /etc/init.d/cgmon)
  status               состояние WAN, пробы, нагрузка
  top                  самые активные устройства
  sites                направления tcp/443 за 5 мин: имена, ответы, клиенты
  trace <ip>...        TCP-трассировка (443) и общий виновник плохих маршрутов
  config-test          проверить конфиг и выйти
  deps [--install]     хватает ли пакетов (kmod-*, tc, curl…) для включённых функций

Установка и настройка:
  --install            мастер: выбор — минимальная, обычная или подробная настройка
  --install-min        минимальная: только пароль страницы, остальное — по умолчанию
  --install-basic      обычная: основное, чего нет на странице (центр сбора, Telegram, шлюзы…)
  --advanced-install   подробная: все параметры по разделам
  --uninstall          снять службу и убрать страницу из /www (конфиг и данные остаются)

Флаги:
  -config ФАЙЛ         конфиг (по умолчанию /etc/cgmon/cgmon.yaml)
  --help-advanced      подробная справка (все команды, файлы, порты, примеры)
  -v, --version        версия

Страница: http://<роутер>/status.html   Конфиг: /etc/cgmon/cgmon.yaml
",
        crate::VERSION
    )
}

pub fn advanced() -> String {
    format!(
        "CGMON(8)                         cgmon {}

ИМЯ
    cgmon — монитор внешнего канала, conntrack/NAT, устройств и трафика для
    роутеров OpenWrt/ImmortalWrt за CGNAT; центр сбора сбоев с нескольких роутеров.

ИСПОЛЬЗОВАНИЕ
    cgmon [daemon|run] [-config ФАЙЛ]
    cgmon КОМАНДА [-config ФАЙЛ]
    cgmon --install | --install-min | --install-basic | --advanced-install [-config ФАЙЛ]

ОПИСАНИЕ
    Демон каждую секунду–пять секунд читает conntrack и счётчики nftables,
    проверяет WAN пробами (TCP 443 к 1.1.1.1/8.8.8.8…), ведёт журнал
    инцидентов, учитывает трафик устройств, может ограничивать новые
    соединения самого агрессивного клиента, вести очередь канала (SQM),
    шейпер отдачи, детекторы блокировок P2P и недоступных сервисов, отправлять
    состояние на центры сбора и сам быть центром (с уведомлениями в Telegram).
    Веб-страница status.html показывает всё это и меняет настройки без
    перезапуска.
    Сам cgmon трафик не маршрутизирует: пакеты пересылает ядро, а cgmon
    по ситуации меняет правила — свои таблицы nftables (fw4 не трогает),
    ip rule и таблицы маршрутов (обход, выбор шлюза), tc (SQM), SmartDNS/
    dnsmasq (DNS-страховка, nftset для обхода). Каналы обхода — уже
    поднятые запасной WAN, tailscale exit node, роутеры в ZeroTier.
    Один процесс, один основной поток (epoll); долгие действия (перезапуск
    SmartDNS, Telegram, проверки путей) — в коротких рабочих потоках.

КОМАНДЫ
    daemon, run       запуск демона (под procd: /etc/init.d/cgmon start)
    status            состояние: фаза WAN (NORMAL/WARNING/CRITICAL/RECOVERY),
                      диагноз, пробы IPv4/IPv6/UDP, conntrack, нагрузка
    top               устройства с наибольшим числом соединений
    probes            результаты последних проб (JSON)
    sites             направления tcp/443 за 5 минут: сервис, ответы/провалы,
                      медиана рукопожатия, адреса, клиенты (down detector)
    trace <ip> [ip...]  TCP-трассировка (SYN на 443 с hop limit 1..20) до адресов
                      и разбор: узел/оператор, через который идут все плохие
                      маршруты и не идёт ни один хороший (path_trace)
    nft-status        таблицы nftables cgmon
    ports             порты: кабель, скорость, дуплекс, сеть (JSON)
    config-test       прочитать и проверить конфиг; код 0 — в порядке
                      (в stderr — недостающие пакеты)
    deps              какие пакеты и модули ядра нужны включённым функциям и
                      каких нет (код 1 — чего-то не хватает)
    deps --install [-y]
                      поставить недостающее через apk (OpenWrt 25+) или opkg;
                      без -y спрашивает подтверждение
    heap              память демона (RSS, данные, потоки)
    disable           выключить активные действия до перезапуска
    telegram-test     пробное сообщение всем получателям центра (hub.telegram)

УСТАНОВКА И НАСТРОЙКА
    Всё, что меняется на странице (пробы, лимитер, QoS, DNS-страховка, оплата,
    cgfinder…), мастер не спрашивает в минимальном и обычном вариантах —
    остаются значения по умолчанию, настраивается потом на странице.
    --install-min     только пароль страницы (Enter — сгенерировать) — и
                      установка службы. Хватает, чтобы роутер заработал.
    --install-basic   пароль; отправка на центр сбора (адрес, общий секрет);
                      этот ли роутер центр (секрет, бот и чаты Telegram, порт);
                      учёт трафика; выбор шлюза; QoS/шейпер — устройство.
    --advanced-install
                      все параметры по разделам с пояснением;
                      Enter — оставить значение, цифра — выбрать вариант,
                      «!» — оставить раздел, «?» — пояснение, «q» — выход без
                      сохранения.
    --install         спросить, какой из трёх вариантов.
    Во всех вариантах: бекап старого файла, запись cgmon.yaml (существующий
    файл правится на месте — комментарии сохраняются; новый — из справочного
    с пояснениями), проверка пакетов, установка службы и запуск.

ФЛАГИ
    -config ФАЙЛ, --config ФАЙЛ
                      путь к конфигу (в любом месте командной строки)
    -h, --help        краткая справка
    --help-advanced   эта справка
    -v, --version     версия

КОНФИГ
    Поиск: -config → $CGMON_CONFIG → /etc/cgmon/cgmon.yaml → /etc/cgmon.yaml →
    /opt/cgmon/cgmon.yaml → /etc/config/cgmon.yaml → встроенные значения.
    Все параметры с пояснениями — config.reference.yaml (он же — основа мастера).
    Изменения со страницы хранятся в /etc/cgmon/runtime.json поверх cgmon.yaml
    (сам cgmon.yaml не переписывается). Секреты (web.password, report.token,
    hub.*) задаются только в cgmon.yaml — права файла 0600.

ФАЙЛЫ
    /opt/cgmon/cgmon                     бинарник
    /etc/init.d/cgmon                    служба procd
    /etc/cgmon/cgmon.yaml                конфиг
    /etc/cgmon/runtime.json              настройки со страницы
    /var/run/cgmon.sock                  сокет команд (status, top, …)
    /var/run/cgmon.status.json           состояние для страницы
    /tmp/cgmon/                          все временные файлы (журналы, учёт, история графика)
    /tmp/cgmon/www/                      страница и CGI из бинарника; в /www — ссылки
    /tmp/cgmon/incidents.jsonl           журнал инцидентов
    /etc/cgmon/acct_state.json           учёт трафика (переживает перезагрузку)
    /etc/cgmon/hub_state.json            центр сбора: роутеры и сбои
    /tmp/cgmon/hub.jsonl                 центр сбора: общий журнал
    /www/status.html, /www/cgi-bin/api_* веб-страница и её CGI

ЦЕНТР СБОРА (hub) И ОТПРАВКА (report)
    Каждый роутер (report.enabled) раз в минуту и при любом изменении шлёт на
    центры из report.urls: состояние WAN, пробы, открытые инциденты, сбои
    сервисов и своего провайдера (AS внешнего IP). Центров может быть
    несколько — данные уходят во все.
    Центр (hub.enabled, галочка «Главный центр сбора») сопоставляет отчёты и
    шлёт в Telegram (hub.telegram: несколько ботов, у каждого несколько чатов —
    уведомление уходит всем): общий сбой внешнего канала (деградация у роутеров ≥2
    разных провайдеров), сбой одного провайдера, сервис не отвечает у многих,
    роутер не на связи; восстановление — с длительностью.

    Порт: TCP 7788 (hub.listen). Для центра в интернете открыть в firewall
    только его: входящий TCP 7788 на WAN.

    Безопасность: каждый отчёт шифруется и подписывается AES-256-GCM ключом из
    общего секрета (report.token = hub.token, ≥16 символов) — секрет по сети не
    передаётся, прочитать/подделать отчёт нельзя. Повтор перехваченного пакета
    отвергается (метка времени ±5 мин, одноразовые номера). Ограничения:
    64 соединения, 8 с одного IP, 120 запросов в минуту с IP, 10 с на запрос,
    тело ≤64 КБ, ≤500 роутеров. На любую ошибку — одинаковый 403. Подробное
    состояние центра наружу не отдаётся (только 127.0.0.1 и страница центра).
    Часы роутеров должны идти верно (NTP): расхождение >5 мин — отчёт отвергнут.
    Секрет общий: утечка с любого роутера позволяет подделывать отчёты —
    при подозрении смените его везде.

ПЕРЕМЕННЫЕ ОКРУЖЕНИЯ
    CGMON_CONFIG      путь к конфигу
    NO_COLOR          без цвета в выводе команд
    CGMON_READONLY=1  ничего не менять в системе (сверка рядом с другим демоном)

КОДЫ ВЫХОДА
    0 — успех; 1 — ошибка (конфиг, демон не запущен, отказ мастера); 2 — неверные
    аргументы.

ПРИМЕРЫ
    Первая установка (только пароль):
        scp -O cgmon root@router:/tmp/ && ssh root@router /tmp/cgmon --install-min
    Проверить конфиг после правки:
        cgmon config-test && /etc/init.d/cgmon restart
    Что сейчас с WAN и кто грузит:
        cgmon status; cgmon top
    Какие сайты не отвечают клиентам:
        cgmon sites
    Ключ для центра сбора (одинаковый на центре и роутерах):
        head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \\n'

ЗАВИСИМОСТИ
    Всегда: nftables (nft), conntrack (/proc/net/nf_conntrack).
    qos / upload_shaper:  tc-tiny, kmod-sched-core (htb, fq_codel, flow,
                          ingress, mirred), kmod-sched-cake, kmod-ifb (приём)
    hard_limit:           kmod-nft-connlimit
    gate_selector:        ip-full
    dns_guard (обход через другой путь): ip-full; curl — проверка
                          загрузки через путь (wget не умеет); relays — ZeroTier
    HTTPS (Telegram, отчёты, TAS-IX, производители): curl, wget
                          или uclient-fetch + libustream-*ssl
    Демон проверяет это раз в минуту: в журнал — «deps: нет …», на странице —
    предупреждение. Установка: cgmon deps --install.

ДИАГНОСТИКА
    logread | grep cgmon                 журнал демона
    cgmon status                         фаза и диагноз
    MONITORING_ONLY первые startup_grace_sec после запуска — норма.
    Страница не обновляется — проверьте /var/run/cgmon.status.json и
    /etc/init.d/cgmon status. Отчёты не доходят до центра — на роутере
    страница «Настройки» показывает ошибку по каждому центру; на центре —
    logread | grep hub.
",
        crate::VERSION
    )
}
